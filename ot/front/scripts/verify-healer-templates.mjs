import assert from "node:assert/strict";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const server = await createServer({ configFile: false, root, logLevel: "error", server: { middlewareMode: true, hmr: false, ws: false }, optimizeDeps: { noDiscovery: true, include: [] } });
try {
 const { makeHealerMember, makeHealerRule, makeHealerSettings, cloneHealerSettings, healerTemplateFromMember, applyHealerTemplate } = await server.ssrLoadModule("/src/healerMonitorTypes.ts");
 const source = makeHealerMember({ id: 'first-session-id', name: 'FirstPlayer' }, 0);
 source.favorite = true; source.health = true; source.healthSettings.threshold = 35;
 source.healthSettings.repeatCount = 3; source.healthSettings.repeatIntervalSeconds = 7;
 source.healthSettings.overlay = { enabled: true, x: -120, y: 220 };
 source.buffSettings.enabled = true;
 source.buffSettings.rules.push(makeHealerRule(680, '战争序曲', 25));
 source.buffSettings.rules[0].repeatCount = 4; source.buffSettings.rules[0].repeatIntervalSeconds = 12;
 source.buffSettings.rules[0].sound = { kind: 'custom', soundId: 'existing-audio', name: '自定义音乐.mp3' };
 source.buffSettings.rules[0].deathLoss = { enabled: false, sound: {kind: 'custom', soundId: 'death-audio', name: '死亡.mp3'}, repeatCount: 3, repeatIntervalSeconds: 9 };
 const template = healerTemplateFromMember(source, 'template-1', '队友1');
 assert.deepEqual(Object.keys(template).sort(), ['id', 'name', 'health', 'healthSettings', 'buffSettings'].sort(), 'templates contain no character identity/favorite fields');
 source.healthSettings.threshold = 80;
 assert.equal(template.healthSettings.threshold, 35, 'saving a template captures independent preferences');
 const second = makeHealerMember({ id: 'second-session-id', name: 'SecondPlayer' }, 1);
 applyHealerTemplate(second, template);
 assert.equal(second.id, 'second-session-id'); assert.equal(second.name, 'SecondPlayer'); assert.equal(second.favorite, false);
 assert.equal(second.key, 'player:SecondPlayer'); assert.equal(second.health, true);
 assert.equal(second.healthSettings.threshold, 35); assert.equal(second.healthSettings.overlay.x, -120);
 assert.equal(second.buffSettings.rules[0].sound.soundId, 'existing-audio');
 assert.equal(second.healthSettings.repeatCount, 3); assert.equal(second.healthSettings.repeatIntervalSeconds, 7);
 assert.equal(second.buffSettings.rules[0].repeatCount, 4); assert.equal(second.buffSettings.rules[0].repeatIntervalSeconds, 12);
 assert.equal(second.buffSettings.rules[0].deathLoss.enabled, false); assert.equal(second.buffSettings.rules[0].deathLoss.sound.soundId, 'death-audio');
 assert.equal(second.buffSettings.rules[0].deathLoss.repeatCount, 3); assert.equal(second.buffSettings.rules[0].deathLoss.repeatIntervalSeconds, 9);
 second.buffSettings.rules[0].deathLoss.sound.soundId = 'another-death-audio';
 assert.equal(template.buffSettings.rules[0].deathLoss.sound.soundId, 'death-audio');
 second.buffSettings.rules[0].warningSeconds = 4;
 second.buffSettings.rules[0].sound.name = 'changed';
 assert.equal(template.buffSettings.rules[0].warningSeconds, 25);
 assert.equal(template.buffSettings.rules[0].sound.name, '自定义音乐.mp3', 'applying a template must not share nested rules or sounds');
 const settings = makeHealerSettings(); settings.templates = [template]; settings.opacityPercent = 55;
 const saved = cloneHealerSettings(JSON.parse(JSON.stringify(settings)));
 assert.equal(saved.templates[0].name, '队友1'); assert.equal(saved.opacityPercent, 55);
 assert.equal(saved.members.length, 0, 'templates do not automatically select players');
 delete settings.templates; delete settings.opacityPercent;
 assert.deepEqual(cloneHealerSettings(settings).templates, []);
 assert.equal(cloneHealerSettings(settings).opacityPercent, 100, 'old settings retain full opacity');
 console.log('Healer templates: independent copy, identity, custom sounds, coordinates, persistence shape and legacy opacity verified');
} finally { await server.close(); }
