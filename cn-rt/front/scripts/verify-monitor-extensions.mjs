import assert from 'node:assert/strict';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const server = await createServer({ configFile: false, root, logLevel: 'error',
    server: { middlewareMode: true, hmr: false, ws: false }, optimizeDeps: { noDiscovery: true } });
const storage = new Map();
globalThis.localStorage = { getItem: key => storage.get(key) ?? null, setItem: (key, value) => storage.set(key, value) };
try {
    const { normalizeBossMechanicAlertSettings: normalize, saveBossMechanicAlertSettings: save, loadBossMechanicAlertSettings: load } = await server.ssrLoadModule('/src/bossMechanicAlert.ts');
    const { requestBossMechanicPreview } = await server.ssrLoadModule('/src/bossMechanicPreview.ts');
    const { loadSkillCooldownSettings, saveSkillCooldownSettings } = await server.ssrLoadModule('/src/skillCooldown.ts');
    const { burstPopupDimensions } = await server.ssrLoadModule('/src/burstReminderView.ts');
    const { makeHealerMember, cloneHealerSettings, makeHealerSettings, makeHealerSelf, healerTemplateFromMember, healerTemplateSummary } = await server.ssrLoadModule('/src/healerMonitorTypes.ts');
    const settings = normalize(null), key = 'miel-green-curtain';
    assert.equal(settings.rules[key].alwaysVisible, false);
    assert.equal(settings.ancientGiantHealthEnabled, false); assert.equal(settings.brontasRocks.enabled, false);
    Object.assign(settings.rules[key], { alwaysVisible: true, persistentStyle: 'bar', persistentX: -150, persistentY: 410, persistentScalePercent: 135, persistentOpacityPercent: 55 });
    Object.assign(settings, { ancientGiantHealthEnabled: true, ancientGiantHealthX: -220, ancientGiantHealthOpacityPercent: 65 });
    Object.assign(settings.brontasRocks, { enabled: true, rotation: 270, x: 320, scalePercent: 150 });
    save(settings); const restored = load();
    assert.equal(restored.rules[key].persistentOpacityPercent, 55); assert.equal(restored.rules[key].persistentX, -150);
    assert.equal(restored.rules[key].alwaysVisible, true); assert.equal(restored.rules[key].persistentStyle, 'bar');
    assert.equal(restored.ancientGiantHealthX, -220); assert.equal(restored.ancientGiantHealthOpacityPercent, 65);
    assert.deepEqual(restored.brontasRocks, settings.brontasRocks);
    let body;
    globalThis.fetch = async (_, init) => { body = JSON.parse(init.body); return { ok: true }; };
    await requestBossMechanicPreview(restored.rules[key], 180, true);
    assert.deepEqual(body, { key, durationSeconds: 8, x: -150, y: 410, scalePercent: 135, passiveStyle: 'bar', opacityPercent: 55 });
    await requestBossMechanicPreview(restored.rules[key], 180);
    assert.equal(body.scalePercent, 180); assert.equal(body.passiveStyle, undefined);
    assert.deepEqual(burstPopupDimensions({ passiveStyle: 'bar' }), { width: 180, height: 30 });
    assert.deepEqual(burstPopupDimensions({ passiveStyle: 'timer' }), { width: 104, height: 34 });
    assert.deepEqual(burstPopupDimensions({ rocks: [{ clock: 12 }, { clock: 9 }] }), { width: 260, height: 180 });
    const own = makeHealerSelf();
    const savedSelf = makeHealerSettings(); savedSelf.members = [own];
    assert.equal(cloneHealerSettings(savedSelf).members[0].self, true);
    assert.equal(own.key, 'self'); assert.equal(own.favorite, true);
    const template = healerTemplateFromMember(own, 'mp', 'MP');
    assert.equal(template.self, undefined);
    assert.match(healerTemplateSummary(template), /魔法值 ≤25%/);
    template.mana = false; assert.match(healerTemplateSummary(template), /魔法值关闭/);
    const old = makeHealerMember({ id: 'old', name: 'Old' }, 0); delete old.mana; delete old.manaSettings;
    const legacy = makeHealerSettings(); legacy.members = [old];
    assert.equal(cloneHealerSettings(legacy).members[0].mana, false);
    assert.equal(cloneHealerSettings(legacy).members[0].manaSettings.threshold, 25);
    storage.set('dilmeter-cn-skill-cooldown-v1', JSON.stringify({ rules: { 59047: { skillId: 59047, enabled: true, barOnly: true }, 59041: { skillId: 59041, enabled: true, cooldownSeconds: 17 } } }));
    const oldCooldowns = loadSkillCooldownSettings();
    assert.equal(oldCooldowns.rules[59047], undefined, 'removed bar cannot resurrect its hidden CD rules');
    assert.equal(oldCooldowns.rules[59041].cooldownSeconds, 17, 'ordinary CD reminders survive');
    console.log('Monitor controls: persistence, legacy defaults, independent preview positions/scale/opacity and dimensions verified');
} finally { await server.close(); }
